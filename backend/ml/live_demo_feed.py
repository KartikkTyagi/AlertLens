def run_live_simulation(delay_seconds: float = 3.5):
    logger.info("=" * 65)
    logger.info("Starting AlertLens Live Real-Time Incident Simulation Feed")
    logger.info("Broadcasting %d demo incidents at %.1fs intervals...", len(DEMO_SCENARIOS), delay_seconds)
    logger.info("Keep your browser dashboard at http://localhost:3000 open!")
    logger.info("=" * 65)

    db = SessionLocal()
    try:
        for idx, scenario in enumerate(DEMO_SCENARIOS, 1):
            incident_id = str(uuid.uuid4())
            now = datetime.now(timezone.utc)

            logger.info(
                "[%d/%d] Simulating incident arrival: %s (%s), severity score %.2f, rank %d...",
                idx,
                len(DEMO_SCENARIOS),
                scenario["mitre_tag"],
                scenario["technique_name"],
                scenario["severity_score"],
                scenario["severity_rank"],
            )

            # Insert incident row — this fires Postgres trigger trg_new_incident immediately
            incident = Incident(
                incident_id=incident_id,
                severity_score=scenario["severity_score"],
                severity_rank=scenario["severity_rank"],
                mitre_tag=scenario["mitre_tag"],
                confidence_tier="actionable",
                created_at=now,
            )
            db.add(incident)
            db.commit()

            # Insert correlated alerts linked to the incident
            for alert_data in scenario["alerts"]:
                alert = Alert(
                    alert_id=str(uuid.uuid4()),
                    timestamp=now,
                    source_ip=alert_data["source_ip"],
                    username=alert_data["username"],
                    event_type=alert_data["event_type"],
                    target_asset=alert_data["target_asset"],
                    asset_criticality=alert_data["asset_criticality"],
                    raw_message=alert_data["raw_message"],
                    incident_id=incident_id,
                )
                db.add(alert)
            db.commit()

            logger.info(" -> Incident %s created with %d alerts (NOTIFY sent).", incident_id[:8], len(scenario["alerts"]))

            if idx < len(DEMO_SCENARIOS):
                logger.info("Waiting %.1f seconds for visual effect on dashboard...\n", delay_seconds)
                time.sleep(delay_seconds)

        logger.info("=" * 65)
        logger.info("Live demo feed completed successfully! All %d incidents delivered.", len(DEMO_SCENARIOS))
        logger.info("=" * 65)
    finally:
        db.close()


if __name__ == "__main__":
    run_live_simulation()
